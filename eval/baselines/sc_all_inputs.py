#!/usr/bin/env python3
"""X8: eval/SC_ALL_INPUTS.md -- SuperCollider's 99 shipped Indigo codes on all 7 inputs (693 rows).

Numbers only, derived from eval/results/baselines-*.csv, the manifest, the input-level oracle CSVs
(baselines-pi-oracle.csv + baselines-pi-oracle-x8.csv) and the native-binary probe
(eval/x_logs/x8_native_probe.csv). A number that cannot be obtained is written "missing".

    .env/bin/python eval/baselines/sc_all_inputs.py
"""
import csv
import math
import os
import re
import statistics
import sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_tables as mt  # noqa: E402

APH = mt.APH
RES = mt.RES
OUT = f"{APH}/eval/SC_ALL_INPUTS.md"
VC, SCM = mt.VC, mt.SC
SC_INPUT = mt.SC_INPUT
INPUTS = ["DAG_100n_100e", "DAG_5n_5e", "counterDAG_5n_5e", "DAG_100n_200e", "DAG_200n_400e",
          "counterDAG_200n_1000e", "power_law_200n_1000e"]
TOOLS = [("SuperCollider", ("supercollider", "")),
         ("cuRace vector-clock", ("cuvein", VC)),
         ("cuRace scalar-clock", ("cuvein", SCM)),
         ("HiRace", ("hirace", "")),
         ("iGUARD", ("iguard", "")),
         ("racecheck", ("racecheck", ""))]
MISSING = "missing"


def read(path):
    if not os.path.exists(path):
        return None
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


runs, meta = mt.load_runs()
man = mt.load_manifest()
ids7 = sorted(i for i, r in man.items() if r["pset"] == "PI" and r["build"] == "sc-subset")
meta7 = {i: (man[i]["pset"], man[i]["program"], man[i]["build"], man[i]["input"]) for i in ids7}
by_input = {g: [i for i in ids7 if meta7[i][3] == g] for g in INPUTS}
launch = {g: " ".join(man[by_input[g][0]]["args"].split()[1:]).replace(" ", "x") for g in INPUTS}

# raw SuperCollider rows (per attempt), old + new files
sc_raw = defaultdict(list)
for p in ("baselines-supercollider.csv", "baselines-supercollider-allinputs.csv"):
    for r in read(f"{RES}/{p}") or []:
        if r["id"] in meta7:
            sc_raw[r["id"]].append(r)

orc = {}
for p in ("baselines-pi-oracle.csv", "baselines-pi-oracle-x8.csv"):
    for r in read(f"{RES}/{p}") or []:
        orc[r["id"]] = r


def conf(ids, tool, mode):
    ms = {i: meta7[i] for i in ids}
    c, lst = mt.confusion(runs, ms, man, ("PI",), tool, mode)
    return c, lst


def cell(c):
    return mt._mcell(c)


def frac(a, b):
    return f"{a}/{b}"


out = []
w = out.append
w("# SC_ALL_INPUTS — SuperCollider's 99 Indigo codes on all 7 inputs\n")
w("_Generated by `eval/baselines/sc_all_inputs.py` (task X8). Numbers only. The artifact's own protocol is the "
  f"`{SC_INPUT}` rows (256x4, 99 rows); the other 6 graphs (594 rows) are the HiRace Table-1 graphs at 256x1024, "
  "the launch every other tool ran on those rows. SuperCollider: 5 attempts per row, RACE if any attempt reports; "
  "native warm-up then best of 3. Cells: `TP/(TP+FN), FP/(FP+TN), TO, ERR` over the 99 codes' labelled rows "
  "(boundsBug codes are unlabelled and excluded from the rates)._\n")

# ---------------------------------------------------------------- 0. completion
w("## 0. Completion of the 594 new rows\n")
new_ids = [i for i in ids7 if meta7[i][3] != SC_INPUT]
got = [i for i in new_ids if i in sc_raw]
fin = [i for i in new_ids if (i, "supercollider", "") in runs and runs[(i, "supercollider", "")]["verdict"] in ("RACE", "CLEAN")]
vc = Counter(runs[(i, "supercollider", "")]["verdict"] for i in new_ids if (i, "supercollider", "") in runs)
w(f"- manifest rows with build=sc-subset: {len(ids7)} ({len(ids7) - len(new_ids)} on `{SC_INPUT}` re-used from the "
  f"earlier run, {len(new_ids)} new)")
w(f"- new rows with at least one attempt row: {len(got)} of {len(new_ids)}; finished (RACE or CLEAN): {len(fin)}; "
  f"verdict counts {dict(sorted(vc.items()))}")
nra = [r for i in new_ids for r in sc_raw.get(i, []) if "runtime-not-attached" in (r.get("notes") or "")]
w(f"- attempt rows with `runtime-not-attached`: {len(nra)} (rows: {len({r['id'] for r in nra})})")
nodes = Counter()
for i in new_ids:
    for r in sc_raw.get(i, [])[:1]:
        m = re.search(r"node=(\S+)", r.get("notes") or "")
        nodes[m.group(1) if m else "no-node"] += 1
w(f"- rows per node: {dict(sorted(nodes.items()))}\n")

# ---------------------------------------------------------------- 1. per input
w("## 1. Per input graph, on the 99 codes\n")
hdr = ["input", "launch", "rows (racy / race-free / unlabelled)"] + [n for n, _ in TOOLS]
w("| " + " | ".join(hdr) + " |")
w("|" + "---|" * len(hdr))


def lab_counts(ids):
    c = Counter((man[i]["label"] or "").upper() for i in ids)
    return f"{len(ids)} ({c['RACE']} / {c['CLEAN']} / {len(ids) - c['RACE'] - c['CLEAN']})"


groups = [(g, launch[g], by_input[g]) for g in INPUTS]
groups.append(("the 6 new graphs", "256x1024", new_ids))
groups.append(("**all 7 inputs (693 rows)**", "", ids7))
for name, la, ids in groups:
    row = [name, la, lab_counts(ids)]
    for _, (t, m) in TOOLS:
        c, _l = conf(ids, t, m)
        row.append(cell(c))
    w("| " + " | ".join(row) + " |")
w("")

# ---------------------------------------------------------------- 2. FNs
BUG = re.compile(r"(atomicBug|guardBug|syncBug|raceBug|RaceBug|boundsBug|[A-Za-z]+Bug)")


def bug_type(prog):
    toks = []
    for t in BUG.findall(prog):
        if t not in toks:
            toks.append(t)
    return "+".join(toks) or "none in name"


def oracle_class(i):
    r = orc.get(i)
    if r is None:
        return "oracle N/A (not run)"
    o = r["oracle"]
    if o == "NO-CONFLICT":
        return "no conflicting pair on the input"
    if o == "CONFLICT":
        return "real miss: never manifested in 5 attempts"
    return f"oracle N/A ({o})"


def attempts(i):
    rs = sc_raw.get(i, [])
    return f"{sum(r['verdict'] == 'RACE' for r in rs)}/{len(rs)}"


w("## 2. Every SuperCollider false negative, classified against the input-level oracle\n")
w("Classes: no conflicting pair on the input (oracle NO-CONFLICT) / real miss: never manifested in 5 attempts "
  "(oracle CONFLICT) / oracle N/A. Oracle: `oracle_pi/oracle_pi.py` at each row's own launch "
  "(`baselines-pi-oracle.csv`, `baselines-pi-oracle-x8.csv`). The planted bug type is the `...Bug` token "
  "in the code name.\n")
fn_ids = []
for g in INPUTS:
    c, l = conf(by_input[g], "supercollider", "")
    fn_ids += l["fn"]
cls = Counter(oracle_class(i) for i in fn_ids)
w(f"Total FNs: {len(fn_ids)}. By class: " + ("; ".join(f"{k}: {v}" for k, v in sorted(cls.items())) or "none") + ".\n")
for g in INPUTS:
    c, l = conf(by_input[g], "supercollider", "")
    k = Counter(oracle_class(i) for i in l["fn"])
    w(f"- `{g}` ({launch[g]}): {len(l['fn'])} FN" + ("" if not k else " — " + "; ".join(f"{a}: {b}" for a, b in sorted(k.items()))))
w("")
if fn_ids:
    w("| id | input | planted bug | attempts reporting | class |")
    w("|---|---|---|---|---|")
    for i in fn_ids:
        w(f"| {i} | {meta7[i][3]} | {bug_type(meta7[i][1])} | {attempts(i)} | {oracle_class(i)} |")
    w("")
# oracle coverage
miss_orc = [i for i in ids7 if (man[i]["label"] or "").upper() == "RACE" and i not in orc]
w(f"Oracle coverage of the 99 codes' racy rows: {sum(1 for i in ids7 if (man[i]['label'] or '').upper() == 'RACE' and i in orc)} "
  f"of {sum(1 for i in ids7 if (man[i]['label'] or '').upper() == 'RACE')} have an oracle row; "
  f"ORACLE-N/A rows: {sum(1 for r in orc.values() if r['oracle'] == 'ORACLE-N/A' and r['id'] in meta7)}; "
  f"no row: {len(miss_orc)}.\n")
unfin = [i for i in ids7 if (i, "supercollider", "") in runs and runs[(i, "supercollider", "")]["verdict"] not in ("RACE", "CLEAN")]
missing_rows = [i for i in ids7 if (i, "supercollider", "") not in runs]
w(f"SuperCollider rows without a verdict (TIMEOUT / ERROR): {len(unfin)}; rows with no result at all: {len(missing_rows)}.")
for i in unfin + missing_rows:
    r = sc_raw.get(i, [{}])[0]
    w(f"- {i}: {runs[(i, 'supercollider', '')]['verdict'] if (i, 'supercollider', '') in runs else MISSING}; {(r.get('notes') or '')[:200]}")
w("")

# ---------------------------------------------------------------- 3. FPs
w("## 3. SuperCollider false positives (label race-free, verdict RACE)\n")
fps = []
for g in INPUTS:
    c, l = conf(by_input[g], "supercollider", "")
    fps += l["fp"]
if not fps:
    w("None: 0 of the race-free-labelled rows that finished.\n")
else:
    w("| id | input | attempts reporting | report ids (file:line:kind) | notes |")
    w("|---|---|---|---|---|")
    for i in fps:
        rr = [r for r in sc_raw.get(i, []) if r["verdict"] == "RACE"]
        w(f"| {i} | {meta7[i][3]} | {attempts(i)} | {(rr[0]['report_ids'] if rr else '')[:300]} | {(rr[0].get('notes') if rr else '')[:120]} |")
    w("")

# ---------------------------------------------------------------- 4. disagreements
w("## 4. Rows where SuperCollider and cuRace disagree\n")
for lbl, cm in (("vector-clock", ("cuvein", VC)), ("scalar-clock", ("cuvein", SCM))):
    both = {"SC RACE / cuRace CLEAN": [], "SC CLEAN / cuRace RACE": []}
    one = []
    for i in ids7:
        a, b = runs.get((i, "supercollider", "")), runs.get((i,) + cm)
        if not a or not b:
            one.append((i, a["verdict"] if a else MISSING, b["verdict"] if b else MISSING))
            continue
        av, bv = a["verdict"], b["verdict"]
        if av in ("RACE", "CLEAN") and bv in ("RACE", "CLEAN"):
            if av != bv:
                both[f"SC {av} / cuRace {bv}"].append(i)
        elif av != bv:
            one.append((i, av, bv))
    w(f"**cuRace {lbl}**: " + "; ".join(f"{k}: {len(v)}" for k, v in both.items()) +
      f"; one side without a verdict: {len(one)}.\n")
    for k, v in both.items():
        if v:
            w(f"- {k} ({len(v)}):")
            for i in v:
                w(f"  - {i} (label {man[i]['label'] or '-'})")
    if one:
        w(f"- one side without RACE/CLEAN ({len(one)}) [id: SC / cuRace]:")
        for i, a, b in one:
            w(f"  - {i}: {a} / {b} (label {man[i]['label'] or '-'})")
    w("")

# ---------------------------------------------------------------- 5. overhead
w("## 5. Overhead of SuperCollider vs its own native binary, per input\n")
w("Slowdown = SuperCollider wall / its native wall (artifact's uninstrumented binary, same container; median of "
  "the 5 attempts over the best of 3 native runs), TIMEOUT/ERROR excluded. Cell = `min / max / avg / mid (geomean), n` "
  "as in table 2 of BASELINES_SUMMARY.md.\n")
rat = mt._ratios(runs, meta)


def ov(ids):
    xs = [rat[(i, "supercollider", "")] for i in ids if (i, "supercollider", "") in rat
          and runs[(i, "supercollider", "")]["verdict"] not in ("TIMEOUT", "ERROR")]
    if not xs:
        return MISSING
    return (f"{min(xs):.1f}× / {max(xs):.1f}× / {sum(xs) / len(xs):.1f}× / {statistics.median(xs):.1f}× "
            f"({mt._geomean(xs):.1f}×), n={len(xs)}")


w("| input | launch | SuperCollider |")
w("|---|---|---|")
for g in INPUTS:
    w(f"| {g} | {launch[g]} | {ov(by_input[g])} |")
w(f"| the 6 new graphs | 256x1024 | {ov(new_ids)} |")
w(f"| **all 7 inputs** | | {ov(ids7)} |")
w("")

# ---------------------------------------------------------------- 6. paper cells
w("## 6. Paper cells whose SuperCollider value changes\n")


def sc_conf(ids):
    c, _l = conf(ids, "supercollider", "")
    return c


c99 = sc_conf(by_input[SC_INPUT])
c693 = sc_conf(ids7)
cP6, _ = mt.confusion(runs, {i: m for i, m in meta.items() if m[0] == "P6"}, man, ("P6",), "supercollider", "")


def tpfp(c):
    tp = f"{c['tp']}/{c['tp'] + c['fn']}" if c["lab_r"] else "—"
    fp = f"{c['fp']}/{c['fp'] + c['tn']}" if c["lab_c"] else "—"
    extra = ("; " + ", ".join(x for x in (f"{c['to']} TO" if c["to"] else "", f"{c['err']} ERR" if c["err"] else "") if x)) \
        if (c["to"] or c["err"]) else ""
    return f"{tp} / {fp}{extra}"


w("Table 4 (`tab:eval-accuracy`) cells are `recall / false-positive rate`, as `TP/(TP+FN)` over `FP/(FP+TN)`. "
  "Old = the cell in the paper draft (origin/main of cuRacePaper, read with `git show`); the old value is "
  f"reproduced from the CSVs for the 99-row view: {tpfp(c99)}.\n")
agg_old = "48/58 / 0/65"
agg_tp = cP6["tp"] + c693["tp"]
agg_tpn = cP6["tp"] + cP6["fn"] + c693["tp"] + c693["fn"]
agg_fp = cP6["fp"] + c693["fp"]
agg_fpn = cP6["fp"] + cP6["tn"] + c693["fp"] + c693["tn"]
agg_err = cP6["to"] + cP6["err"] + c693["to"] + c693["err"]
w("| cell | old | new | note |")
w("|---|---|---|---|")
w(f"| Table 4, row \"Indigo 1.3, SC's 99\", SuperCollider | 39/45 / 0/44 | {tpfp(c693)} | the row taken as 99 codes × 7 inputs "
  f"({len(ids7)} program-inputs; the paper row counts 99). Unchanged if the row stays the artifact-protocol 99: {tpfp(c99)} |")
w(f"| Table 4, row \"Indigo 1.3\" (all 590 codes), SuperCollider | — | — | the artifact ships binaries for 99 of the 590 codes only; "
  f"the {len(ids7)} rows are a subset of that row's 4,130 |")
w(f"| Table 4, row \"All pre-registered\", SuperCollider | {agg_old} | {agg_tp}/{agg_tpn} / {agg_fp}/{agg_fpn}"
  f"{'; ' + str(agg_err) + ' TO/ERR' if agg_err else ''} | cuHadron SC cell ({tpfp(cP6)}) plus the Indigo cell above; "
  f"if the Indigo row stays at 99: 48/58 / 0/65 |")
w("| Table 4, rows cuHadron, HeCBench SC's 10, SuperCollider | unchanged | unchanged | not touched by this task |")
w("| Union table (`tab:eval-accuracy-union`), SuperCollider column | Indigo 1.3: —; cuHadron 9/13, 0/21; HeCBench 5/5, 0/5 | unchanged | "
  "Indigo 1.3 has no strong conflicts, so the union counting gives the same cell as Table 4 for these rows; the union table has "
  "no SC's-99 row to change |")
w("")
fnn = len(fn_ids)
real = sum(1 for i in fn_ids if oracle_class(i).startswith("real miss"))
noc = sum(1 for i in fn_ids if oracle_class(i).startswith("no conflicting"))
na = fnn - real - noc
c99_fn = conf(by_input[SC_INPUT], "supercollider", "")[1]["fn"]
real99 = sum(1 for i in c99_fn if oracle_class(i).startswith("real miss"))
w(f"Old sentence: \"it misses 6 races on its Indigo 1.3 subset, 4 of which have a conflicting pair on the input\" — from the CSVs, "
  f"on the 99 rows: {len(c99_fn)} FN, {real99} real misses.\n")
fpn = c693["fp"]
w(f"New sentence (numbers from this run): \"SuperCollider reports {'no false positive' if not fpn else str(fpn) + ' false positives'} on the programs it ships; "
  f"on its 99 Indigo 1.3 codes over seven inputs ({len(ids7)} program-inputs) it misses {fnn} of {c693['tp'] + c693['fn']} races, "
  f"{real} of which have a conflicting pair on the input"
  f"{'' if not na else f' and {na} of which the oracle cannot decide'}"
  f", {noc} have none\"" + (f"; {c693['to'] + c693['err']} rows did not finish." if (c693['to'] + c693['err']) else ".") + "\n")

# ---------------------------------------------------------------- 7. comparability
w("## 7. Comparability: the six HiRace graphs at 256x1024\n")
probe = read(f"{APH}/eval/x_logs/x8_native_probe.csv")
if probe is None:
    w(f"Native-binary probe: {MISSING} (eval/x_logs/x8_native_probe.csv not present).\n")
else:
    bad = [r for r in probe if r["timeout"] == "1" or (r["rc"] not in ("0",))]
    use = [r for r in probe if "usage" in r["first_line"].lower()]
    per = Counter(r["input"] for r in probe)
    w(f"The artifact's authors ran their binaries on `{SC_INPUT}` at 256x4 only. The probe ran each row's NATIVE (uninstrumented) "
      f"binary once at the manifest launch: {len(probe)} rows probed ({', '.join(f'{g}: {per[g]}' for g in INPUTS)}).")
    w(f"- native binary exited non-zero or timed out: {len(bad)} rows"
      + ("" if not bad else " — " + "; ".join(f"{r['id']} rc={r['rc']} to={r['timeout']} `{r['first_line'][:60]}`" for r in bad[:20])))
    w(f"- native binary printed a usage message: {len(use)} rows"
      + ("" if not use else " — " + "; ".join(f"{r['id']} `{r['first_line'][:60]}`" for r in use[:20])))
    w(f"- node(s): {sorted({r['node'] for r in probe})}\n")
sc_unfin_by_input = Counter(meta7[i][3] for i in unfin + missing_rows)
w(f"SuperCollider rows without a RACE/CLEAN verdict by input: {dict(sorted(sc_unfin_by_input.items())) or 'none'}.")
sc_tp_by = {g: conf(by_input[g], 'supercollider', '')[0] for g in INPUTS}
w("SuperCollider recall per input: " + "; ".join(f"{g} {frac(c['tp'], c['tp'] + c['fn'])}" for g, c in sc_tp_by.items()) + ".\n")

with open(OUT, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", OUT)

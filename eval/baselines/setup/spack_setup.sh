#!/usr/bin/env bash
# Spack bootstrap for the iGUARD README dependencies that the cluster lacks.
#
# iGUARD's README asks for `wget bc gcc time gawk libtbb-dev`. On this cluster
# wget/bc/gawk/gcc exist; GNU `time` and the TBB *headers* do not (only
# libtbb.so.2 runtime). The detector itself (detector/*.cu) includes only NVBit
# headers + libstdc++, so these packages serve iGUARD's benchmark scripts, not
# the detector build; they are installed here as instructed so the environment
# matches the README. Everything is logged verbatim to setup/spack.status.
#
#   sbatch -p normal -N1 -n1 -c 8 -t 03:00:00 -o build_logs/spack_setup-%j.log \
#       eval/baselines/setup/spack_setup.sh
set -u
REPO=/home/fzheng4/AccelProf
cd "$REPO/eval/baselines/setup" || exit 1
STATUS="$PWD/spack.status"; : > "$STATUS"
log(){ echo "$@" | tee -a "$STATUS"; }
SPACK_ROOT="${SPACK_ROOT:-$HOME/spack}"
log "spack_setup $(date -Is) node=$(hostname) SPACK_ROOT=$SPACK_ROOT"
if [ ! -x "$SPACK_ROOT/bin/spack" ]; then
  log "\$ git clone -c feature.manyFiles=true --depth 2 https://github.com/spack/spack.git $SPACK_ROOT"
  git clone -c feature.manyFiles=true --depth 2 https://github.com/spack/spack.git "$SPACK_ROOT" 2>&1 | tail -3 | tee -a "$STATUS"
  [ -x "$SPACK_ROOT/bin/spack" ] || { log "FAIL: spack clone"; exit 3; }
fi
# shellcheck disable=SC1091
. "$SPACK_ROOT/share/spack/setup-env.sh"
log "spack version: $(spack --version 2>&1)"
log "\$ spack compiler find"
spack compiler find 2>&1 | tail -3 | tee -a "$STATUS"
log "\$ spack external find --not-buildable cuda gcc python git bc gawk wget"
spack external find --not-buildable cuda gcc python git bc gawk wget 2>&1 | tail -5 | tee -a "$STATUS"
rc=0
for pkg in time intel-tbb; do
  log "\$ spack install -j8 $pkg"
  if spack install -j8 "$pkg" >>"$STATUS" 2>&1; then
    log "OK: $pkg -> $(spack location -i "$pkg" 2>/dev/null)"
  else
    log "FAIL: spack install $pkg (last lines follow)"; tail -20 "$STATUS" | sed 's/^/    /' ; rc=3
  fi
done
log "\$ spack find"
spack find 2>&1 | tee -a "$STATUS"
# expose the installed bins/headers for anything that sources this status file's env
{
  echo "# generated by spack_setup.sh $(date -Is)"
  echo "export SPACK_ROOT=$SPACK_ROOT"
  echo ". $SPACK_ROOT/share/spack/setup-env.sh"
  for pkg in time intel-tbb; do
    d=$(spack location -i "$pkg" 2>/dev/null) && echo "export PATH=$d/bin:\$PATH; export CPATH=$d/include:\${CPATH:-}; export LIBRARY_PATH=$d/lib:\${LIBRARY_PATH:-}; export LD_LIBRARY_PATH=$d/lib:\$LD_LIBRARY_PATH"
  done
} > "$PWD/spack_env.sh"
log "wrote $PWD/spack_env.sh; rc=$rc"
exit $rc

#!/usr/bin/env python3
"""T21b: render eval/realworld/triage_queue.md from eval/results/realworld/triage_inputs.json and other_reports.csv
(written by rw_score.py --write). Misses and DETECTED-AS cases with the proposed cause, fixed-build reports (STILL-REPORTED and
RESIDUAL-AS-EXPECTED), and the count of other reports per target. Facts only; no triage verdicts are made here."""
import csv, json, os, collections
WT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
R = f"{WT}/eval/results/realworld"
q = json.load(open(f"{R}/triage_inputs.json"))
out = ["# T21b triage queue (for the Opus triage; nothing here is counted before it)", "",
       "Generated by `eval/realworld/harness/rw_queue.py` from `eval/results/realworld/triage_inputs.json`. Proposed causes are Sonnet's from the",
       "attribution evidence; they are not verdicts.", ""]
miss = [e for e in q["queue_miss"] if e["kind"] == "MISSED"]
das = [e for e in q["queue_miss"] if e["kind"] == "DETECTED-AS"]
out += [f"## A. Misses on buggy builds ({len(miss)} rows)", "", "| target | mode | flavor | component | run | proposed cause |", "|---|---|---|---|---|---|"]
for e in miss:
    out.append(f"| {e['target']} | {e['mode']} | {e['flavor']} | {e['component']} | {e['run_verdict']} | {e['miss_cause']} |")
    for v in (e.get("evidence") or [])[:3]:
        out.append(f"|  | | | | | evidence: {v.get('verdict')}/{v.get('hb_class')} {v.get('cur_frames')} vs {v.get('anc_frames')} |")
out += ["", f"## B. DETECTED-AS-<other class> on buggy builds ({len(das)} rows; D20 option (i))", "", "| target | mode | component | outcome | .STRONG in SASS | reports |", "|---|---|---|---|---|---|"]
for e in das:
    out.append(f"| {e['target']} | {e['mode']} | {e['component']} | {e['outcome']} | {e.get('strong_token')} | {' ; '.join(e['reports'][:2])} |")
fx = q["queue_fixed"]
sr = [e for e in fx if e["kind"] == "STILL-REPORTED"]
ra = [e for e in fx if e["kind"] == "RESIDUAL-AS-EXPECTED"]
out += ["", f"## C. STILL-REPORTED on fixed builds ({len(sr)} rows)", ""]
for e in sr:
    out.append(f"- **{e['target']}** ({e['mode']}, {e['flavor']}): oracle fixed = `{e['oracle_fixed']}`; matched `{e['matched']}`; {len(e['reports'])} report(s), first:  `{e['reports'][0]}`")
out += ["", f"## D. RESIDUAL-AS-EXPECTED on fixed builds ({len(ra)} rows; the oracle registers a residual; listed so the residual's identity is checked)", ""]
for e in ra:
    out.append(f"- {e['target']} ({e['mode']}, {e['flavor']}): `{e['matched']}`, .STRONG in SASS: {e['strong_token']}; first: `{e['reports'][0][:300]}`")
cnt = collections.Counter()
if os.path.exists(f"{R}/other_reports.csv"):
    for r in csv.DictReader(open(f"{R}/other_reports.csv")):
        cnt[(r["target"], r["variant"], r["mode"], r["flavor"])] += 1
out += ["", "## E. Other reports (no oracle, residual or both-builds pair explains them; not scored; for T21c's queue)", "",
        "Rows are in `eval/results/realworld/other_reports.csv`. Counts per target x variant x mode (main flavor):", "", "| target | variant | vector-clock | scalar-clock |", "|---|---|---|---|"]
keys = sorted({(t, v) for (t, v, m, f) in cnt})
for t, v in keys:
    out.append(f"| {t} | {v} | {cnt.get((t,v,'vector-clock','main'),0)} | {cnt.get((t,v,'scalar-clock','main'),0)} |")
open(f"{WT}/eval/realworld/triage_queue.md", "w").write("\n".join(out) + "\n")
print("triage_queue.md written:", len(miss), "misses,", len(das), "detected-as,", len(sr), "still-reported,", len(ra), "residual")

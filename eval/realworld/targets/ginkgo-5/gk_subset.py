#!/usr/bin/env python3
"""gk_subset.py -- compile a SUBSET of a CMake project's translation units with the project's own compile commands.

    gk_subset.py <compile_commands.json> <src-root> <outdir> <extra-cxx-flags|-> <extra-nvcc-flags|-> <source-relative-to-src-root>...

For each source the entry of compile_commands.json (generated by the project's own `cmake` configure step, with the
project's flags/defines/includes) is looked up; the command is re-run with the output redirected to <outdir>/<n>.o and the
EXTRA flags appended (same extra flags for every variant).  Prints one line per object: "<n>.o <source> rc=<rc>".
Runs the compiles in parallel (NJOBS)."""
import json, os, shlex, subprocess, sys
from concurrent.futures import ThreadPoolExecutor


def main():
    ccj, src, out, xcxx, xnvcc = sys.argv[1:6]
    wanted = sys.argv[6:]
    os.makedirs(out, exist_ok=True)
    entries = {}
    for e in json.load(open(ccj)):
        f = os.path.relpath(os.path.realpath(e["file"]), os.path.realpath(src))
        entries.setdefault(f, e)
    jobs = []
    for i, w in enumerate(wanted):
        e = entries.get(w)
        if e is None:
            print("NO compile_commands entry for", w)
            return 2
        args = shlex.split(e["command"])
        # drop -o X -c X (re-added)
        cleaned, skip = [], False
        for a in args:
            if skip:
                skip = False
                continue
            if a == "-o":
                skip = True
                continue
            if a == "-c":
                skip = True
                continue
            cleaned.append(a)
        is_nvcc = os.path.basename(cleaned[0]).startswith("nvcc")
        extra = shlex.split(xnvcc if is_nvcc else xcxx) if (xnvcc if is_nvcc else xcxx) != "-" else []
        obj = os.path.join(os.path.abspath(out), "%02d_%s.o" % (i, os.path.basename(w)))
        jobs.append((obj, w, cleaned + extra + ["-c", e["file"], "-o", obj], e["directory"]))

    def run(j):
        obj, w, cmd, d = j
        r = subprocess.run(cmd, cwd=d, capture_output=True, text=True)
        if r.returncode:
            open(obj + ".err", "w").write(" ".join(shlex.quote(c) for c in cmd) + "\n" + r.stdout + r.stderr)
        return "%s %s rc=%d" % (os.path.basename(obj), w, r.returncode), r.returncode

    nj = int(os.environ.get("NJOBS", "8"))
    rc = 0
    with ThreadPoolExecutor(nj) as ex:
        for line, r in ex.map(run, jobs):
            print(line, flush=True)
            rc |= (r != 0)
    return rc


if __name__ == "__main__":
    sys.exit(main())
